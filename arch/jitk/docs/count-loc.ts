import { readFileSync, writeFileSync } from 'node:fs';
import { relative, extname, basename } from 'node:path';
import { ROOT } from './dispatch.ts';
import { files, sha, json } from './lib.ts';

const skip = new Set(['.git', 'node_modules', 'target', 'vendor', 'payload', 'out', 'build', 'dist', '__pycache__', 'evidence', 'results', '.venv']);
const extensions = new Set(['.rs', '.S', '.s', '.c', '.h', '.py', '.js', '.mjs', '.ts', '.sh', '.ld', '.sb', '.lua', '.toml']);
const subtrees = new Set(['kernel', 'vmm', 'executor', 'protocol', 'grow', 'bench', 'linux', 'docs', 'mcp']);
interface Item {
  path: string;
  component: string;
  kind: string;
  lines: number;
  sha256: string;
}
interface Patch {
  path: string;
  sha256: string;
  added: number;
  removed: number;
}
interface Counts {
  'implementation/build': number;
  test: number;
  total: number;
}
function lines(text: string): string[] {
  const rows = text.split(/\r\n|[\n\r\v\f\u001c-\u001e\u0085\u2028\u2029]/);
  if (rows[rows.length - 1] === '') {
    rows.pop();
  }
  return rows;
}

const inventory: Item[] = [];
const patches: Patch[] = [];
for (const path of files(ROOT).sort()) {
  const rel = relative(ROOT, path);
  const parts = rel.split('/');
  if (parts.some(part => skip.has(part)) || basename(path).includes('generated')) {
    continue;
  }
  const data = readFileSync(path);
  const text = data.toString('utf8');
  if (extname(path) === '.diff') {
    const rows = lines(text);
    patches.push({ path: rel, sha256: sha(data), added: rows.filter(line => line.startsWith('+') && !line.startsWith('+++')).length, removed: rows.filter(line => line.startsWith('-') && !line.startsWith('---')).length });
    continue;
  }
  if (!extensions.has(extname(path)) && !['Makefile', 'Dockerfile', 'init'].includes(basename(path))) {
    continue;
  }
  if (!subtrees.has(parts[0]) && rel !== 'Makefile') {
    continue;
  }
  const head = data.subarray(0, 200).toString();
  if (head.includes('Generated by') || head.includes('DO NOT EDIT')) {
    continue;
  }
  let component = parts.length > 1 ? parts[0] : 'integration';
  for (const prefix of ['vmm/sandbox', 'executor/policy', 'bench/hyperlight']) {
    if (rel.startsWith(prefix + '/')) {
      component = prefix;
    }
  }
  const stem = basename(path, extname(path));
  const test = parts.some(part => ['test', 'tests', 'fixtures', 'guest', 'hostile'].includes(part)) || ['test', 'check', 'hostile'].some(word => stem.includes(word)) || stem.startsWith('fixture') || ['verify', 'type-proof', 'wrapper-conformance'].includes(stem);
  inventory.push({ path: rel, component, kind: test ? 'test' : 'implementation/build', lines: lines(text).length, sha256: sha(data) });
}
const counts = new Map<string, Counts>();
const hashes = new Map<string, string[]>();
for (const item of inventory) {
  const row = counts.get(item.component) || { 'implementation/build': 0, test: 0, total: 0 };
  if (item.kind === 'test') {
    row.test += item.lines;
  } else {
    row['implementation/build'] += item.lines;
  }
  row.total += item.lines;
  counts.set(item.component, row);
  const group = hashes.get(item.sha256) || [];
  group.push(item.path);
  hashes.set(item.sha256, group);
}
const components: Record<string, Counts> = {};
for (const name of [...counts.keys()].sort()) {
  components[name] = counts.get(name)!;
}
const total = inventory.reduce((sum, item) => sum + item.lines, 0);
const result = {
  measured_utc: new Date().toISOString().replace('Z', '000+00:00'),
  method: 'physical lines incl blanks/comments; owned source/build scripts/config and test code; no vendor/generated/data/output; owned fixture code included',
  components,
  total,
  files: inventory,
  upstream_patch_deltas_excluded_from_total: patches,
  identical_source_groups: [...hashes.values()].filter(group => group.length > 1)
};
if (process.argv[2] === '--json') {
  writeFileSync(process.argv[3], json(result) + '\n');
}
console.log('Component | implementation/build | tests | total physical LOC');
for (const name of [...counts.keys()].sort()) {
  const row = counts.get(name)!;
  console.log(`${name} | ${row['implementation/build']} | ${row.test} | ${row.total}`);
}
console.log(`TOTAL | | | ${total}`);
console.log('Excluded: vendor, generated files, data, outputs, binaries; owned fixture code included; no whole-product 1.5k claim.');
for (const patch of patches) {
  console.log(`Upstream patch (separate): ${patch.path} +${patch.added}/-${patch.removed}`);
}
