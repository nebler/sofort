#!/usr/bin/env python3
"""Physical owned-source LOC, including comments/blanks, builds and tests.

Vendor/generated/data/binary/output files are excluded, never deduplicated away.
Every included file has a hash and classification in the JSON receipt.
"""
import argparse
from collections import defaultdict
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP = {".git", "node_modules", "target", "vendor", "payload", "out", "build",
        "dist", "__pycache__", "evidence", "results", ".venv"}
EXTENSIONS = {".rs", ".S", ".s", ".c", ".h", ".py", ".js", ".mjs", ".ts",
              ".sh", ".ld", ".sb", ".lua", ".toml"}
SUBTREES = {"kernel", "vmm", "executor", "protocol", "grow", "bench", "linux", "docs", "mcp"}


def inventory():
    files = []
    patches = []
    for path in sorted(ROOT.rglob("*")):
        rel = path.relative_to(ROOT)
        if path.is_symlink() or not path.is_file() or set(rel.parts) & SKIP:
            continue
        if "generated" in path.name:
            continue
        if path.suffix == ".diff":
            data = path.read_bytes()
            lines = data.decode().splitlines()
            patches.append({"path": rel.as_posix(),
                            "sha256": hashlib.sha256(data).hexdigest(),
                            "added": sum(line.startswith("+") and not line.startswith("+++") for line in lines),
                            "removed": sum(line.startswith("-") and not line.startswith("---") for line in lines)})
            continue
        if path.suffix not in EXTENSIONS and path.name not in {"Makefile", "Dockerfile", "init"}:
            continue
        if rel.parts[0] not in SUBTREES and rel.as_posix() != "Makefile":
            continue
        data = path.read_bytes()
        if b"Generated by" in data[:200] or b"DO NOT EDIT" in data[:200]:
            continue
        component = rel.parts[0] if len(rel.parts) > 1 else "integration"
        for prefix in ("vmm/sandbox", "executor/policy", "bench/hyperlight"):
            if rel.as_posix().startswith(prefix + "/"):
                component = prefix
        test = (any(p in {"test", "tests", "fixtures", "guest", "hostile"} for p in rel.parts)
                or "test" in path.stem or "check" in path.stem
                or "hostile" in path.stem or path.stem.startswith("fixture")
                or path.stem in {"verify", "type-proof", "wrapper-conformance"})
        files.append({"path": rel.as_posix(), "component": component,
                      "kind": "test" if test else "implementation/build",
                      "lines": len(data.splitlines()),
                      "sha256": hashlib.sha256(data).hexdigest()})
    components = defaultdict(lambda: {"implementation/build": 0, "test": 0, "total": 0})
    hashes = defaultdict(list)
    for item in files:
        components[item["component"]][item["kind"]] += item["lines"]
        components[item["component"]]["total"] += item["lines"]
        hashes[item["sha256"]].append(item["path"])
    return {"measured_utc": datetime.now(timezone.utc).isoformat(),
            "method": "physical lines incl blanks/comments; owned source/build scripts/config and test code; no vendor/generated/data/output; owned fixture code included",
            "components": dict(sorted(components.items())),
            "total": sum(f["lines"] for f in files), "files": files,
            "upstream_patch_deltas_excluded_from_total": patches,
            "identical_source_groups": [v for v in hashes.values() if len(v) > 1]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", type=Path, help="write full reproducible inventory")
    args = parser.parse_args()
    result = inventory()
    if args.json:
        args.json.write_text(json.dumps(result, indent=2) + "\n")
    print("Component | implementation/build | tests | total physical LOC")
    for component, row in result["components"].items():
        print(f"{component} | {row['implementation/build']} | {row['test']} | {row['total']}")
    print(f"TOTAL | | | {result['total']}")
    print("Excluded: vendor, generated files, data, outputs, binaries; owned fixture code included; no whole-product 1.5k claim.")
    for patch in result["upstream_patch_deltas_excluded_from_total"]:
        print(f"Upstream patch (separate): {patch['path']} +{patch['added']}/-{patch['removed']}")


if __name__ == "__main__":
    main()
