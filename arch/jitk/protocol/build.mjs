import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const path=new URL('dispatcher.js',import.meta.url);
const generated='// Generated by build.mjs from dispatcher.ts; DO NOT EDIT.\n'+
  stripTypeScriptTypes(readFileSync(new URL('dispatcher.ts',import.meta.url),'utf8'));
if(process.env.JITK_RECORD==='1')writeFileSync(path,generated);
else assert.equal(readFileSync(path,'utf8'),generated,'stale dispatcher.js; review and run JITK_RECORD=1 node build.mjs');
