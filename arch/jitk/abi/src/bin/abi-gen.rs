//! Emits the non-Rust copies of the jitk ABI from the `jitk_abi` crate:
//!
//!   executor/abi.ts                   ABI_VERSION, IPC kinds/geometry/bounds, arena classes
//!   executor/ipc/bridge_abi.h         IPC geometry for the N-API bridge
//!   kernel/ring-bootstrap.js          from kernel/ring-bootstrap.js.in
//!   kernel/payload/ring-rng/checkpoint.h  from checkpoint.h.in
//!   executor/shard-helpers.js         from shard-helpers.js.in (prepared guest helpers)
//!
//! The three guest files are templates (`{{NAME}}` placeholders, `{{! ...}}`
//! comment lines) so that their output stays byte-identical to the checked-in
//! guest sources that the ring kernel image and the snapshot helper hash
//! embed. `abi-gen [ROOT]` writes; `abi-gen --check [ROOT]` fails on any stale
//! file. ROOT defaults to arch/jitk (this crate's parent).
use jitk_abi::{ABI_VERSION, arena::Class, ipc, ring};
use std::{
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
    process::ExitCode,
};

const HEADER: &str = "GENERATED by abi/src/bin/abi-gen.rs from the jitk-abi crate (abi/src/lib.rs); do not edit.\n\
Regenerate with `make -C arch/jitk/abi gen`; `make -C arch/jitk/abi test` fails while it is stale.";

/// Placeholders the guest templates may use.
fn placeholders() -> Vec<(&'static str, String)> {
    let v = |n: usize| n.to_string();
    vec![
        ("ABI_VERSION", ABI_VERSION.to_string()),
        ("SOURCE_LIMIT", v(ring::SOURCE_LIMIT)),
        ("MAX_CALLS", v(ring::MAX_CALLS)),
        ("CALL_BYTES", v(ring::CALL_BYTES)),
        ("REPLY_BYTES", v(ring::REPLY_BYTES)),
        ("FD_CHECKPOINT", v(ring::FD_CHECKPOINT)),
        ("FD_REPAIR", v(ring::FD_REPAIR)),
        ("FD_FINISH", v(ring::FD_FINISH)),
        ("FD_CALL_BASE", v(ring::FD_CALL_BASE)),
        ("REPAIR_BYTES", v(ring::REPAIR_BYTES)),
        (
            "CHECKPOINT_RECEIPT_BYTES",
            v(ring::CHECKPOINT_RECEIPT_BYTES),
        ),
    ]
}

fn expand(template: &str, name: &str) -> Result<String, String> {
    let table = placeholders();
    let mut out = String::new();
    for line in template.split_inclusive('\n') {
        if line.starts_with("{{!") {
            continue;
        }
        let mut rest = line;
        while let Some(at) = rest.find("{{") {
            out.push_str(&rest[..at]);
            let end = rest[at..]
                .find("}}")
                .ok_or_else(|| format!("{name}: unterminated placeholder"))?;
            let key = &rest[at + 2..at + end];
            let value = table
                .iter()
                .find(|(k, _)| *k == key)
                .ok_or_else(|| format!("{name}: unknown placeholder {{{{{key}}}}}"))?;
            out.push_str(&value.1);
            rest = &rest[at + end + 2..];
        }
        out.push_str(rest);
    }
    Ok(out)
}

fn typescript() -> String {
    let mut s = String::new();
    for line in HEADER.lines() {
        writeln!(s, "// {line}").unwrap();
    }
    writeln!(s, "\n/** Bumped with any peer-visible ABI change; READY and the prepared snapshot identity carry it. */").unwrap();
    writeln!(s, "export const ABI_VERSION={ABI_VERSION};").unwrap();
    let rows: &[(&str, u64, &str)] = &[
        ("start", ipc::START.into(), "message kinds: Node -> shard"),
        ("reply", ipc::REPLY.into(), ""),
        ("cancel", ipc::CANCEL.into(), ""),
        ("call", ipc::CALL.into(), "message kinds: shard -> Node"),
        ("done", ipc::DONE.into(), ""),
        ("error", ipc::ERROR.into(), ""),
        ("released", ipc::RELEASED.into(), ""),
        ("ready", ipc::READY.into(), ""),
        ("ping", ipc::PING.into(), ""),
        ("stats", ipc::STATS.into(), ""),
        ("headerBytes", ipc::HEADER_BYTES as u64, "record geometry"),
        ("payload", ipc::PAYLOAD as u64, ""),
        ("capacity", ipc::CAPACITY, ""),
        (
            "slots",
            ipc::MAX_SLOTS as u64,
            "physical sandbox slots per shard",
        ),
        (
            "readyBytes",
            ipc::READY_BYTES as u64,
            "READY payload: ABI_VERSION u32 LE",
        ),
        (
            "startHeaderBytes",
            ipc::START_HEADER_BYTES as u64,
            "START payload header before the source",
        ),
        ("deadlineHorizonNs", ipc::DEADLINE_HORIZON_NS, ""),
        ("calls", ring::MAX_CALLS as u64, "per-run guest limits"),
        ("callBytes", ring::CALL_BYTES as u64, ""),
        ("replyBytes", ring::REPLY_BYTES as u64, ""),
        ("doneBytes", ring::DONE_BYTES as u64, ""),
        ("sourceBytes", ring::SOURCE_LIMIT as u64, ""),
        ("errorBytes", ipc::ERROR_BYTES as u64, ""),
        ("statsFixedBytes", ipc::STATS_FIXED_BYTES as u64, ""),
        ("statsRoundTrips", ipc::STATS_ROUND_TRIPS as u64, ""),
        (
            "recordsPerGeneration",
            ipc::RECORDS_PER_GENERATION as u64,
            "queue bounds",
        ),
        ("outbound", ipc::OUTBOUND as u64, ""),
    ];
    writeln!(s, "/** Node <-> shard IPC (ipc/ABI.md). */").unwrap();
    writeln!(s, "export const IPC=Object.freeze({{").unwrap();
    for (key, value, comment) in rows {
        if !comment.is_empty() {
            writeln!(s, "  // {comment}").unwrap();
        }
        assert!(*value <= (1 << 53), "{key} is not a safe JS integer");
        writeln!(s, "  {key}:{value},").unwrap();
    }
    writeln!(s, "}});").unwrap();
    writeln!(
        s,
        "/** Arena classes of prepared snapshots: the START reservation and the writable arena. */"
    )
    .unwrap();
    writeln!(s, "export const ARENA_CLASSES=Object.freeze({{").unwrap();
    for c in Class::ALL {
        writeln!(
            s,
            "  '{}':Object.freeze({{admissionBytes:{},arenaBytes:{}}}),",
            c.name(),
            c.admission_bytes(),
            c.bytes()
        )
        .unwrap();
    }
    writeln!(s, "}});").unwrap();
    s
}

fn c_header() -> String {
    let mut s = String::from("/* ");
    s.push_str(&HEADER.replace('\n', "\n * "));
    s.push_str(" */\n#ifndef JITK_BRIDGE_ABI_H\n#define JITK_BRIDGE_ABI_H\n");
    let rows: &[(&str, u64)] = &[
        ("JITK_ABI_VERSION", ABI_VERSION.into()),
        ("JITK_IPC_CAPACITY", ipc::CAPACITY),
        ("JITK_IPC_PAYLOAD", ipc::PAYLOAD as u64),
        ("JITK_IPC_HEADER_BYTES", ipc::HEADER_BYTES as u64),
        ("JITK_IPC_DATA", ipc::DATA as u64),
        ("JITK_IPC_BYTES", ipc::BYTES as u64),
        ("JITK_IPC_LENGTH_AT", ipc::LENGTH_AT as u64),
        ("JITK_IPC_RESERVED_AT", ipc::RESERVED_AT as u64),
    ];
    for (name, value) in rows {
        writeln!(s, "#define {name} {value}u").unwrap();
    }
    // Cursor names from Node's side: Node produces the shard's RX queue.
    s.push_str("/* Cursors (u64): Node -> shard queue, then shard -> Node queue. */\n");
    for (name, value) in [
        ("JITK_IPC_NODE_PRODUCED", ipc::RX_PRODUCER),
        ("JITK_IPC_SHARD_CONSUMED", ipc::RX_CONSUMER),
        ("JITK_IPC_SHARD_PRODUCED", ipc::TX_PRODUCER),
        ("JITK_IPC_NODE_CONSUMED", ipc::TX_CONSUMER),
    ] {
        writeln!(s, "#define {name} {value}u").unwrap();
    }
    s.push_str("#endif\n");
    s
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let check = args.iter().any(|a| a == "--check");
    let root = args
        .iter()
        .find(|a| !a.starts_with("--"))
        .map(PathBuf::from)
        .unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join(".."));
    let mut outputs: Vec<(&str, Result<String, String>)> = vec![
        ("executor/abi.ts", Ok(typescript())),
        ("executor/ipc/bridge_abi.h", Ok(c_header())),
    ];
    for (out, template) in [
        ("kernel/ring-bootstrap.js", "kernel/ring-bootstrap.js.in"),
        ("executor/shard-helpers.js", "executor/shard-helpers.js.in"),
        (
            "kernel/payload/ring-rng/checkpoint.h",
            "kernel/payload/ring-rng/checkpoint.h.in",
        ),
    ] {
        let text = fs::read_to_string(root.join(template))
            .map_err(|e| format!("{template}: {e}"))
            .and_then(|t| expand(&t, template));
        outputs.push((out, text));
    }
    let mut failed = false;
    for (path, text) in outputs {
        let text = match text {
            Ok(text) => text,
            Err(e) => {
                eprintln!("abi-gen: {e}");
                failed = true;
                continue;
            }
        };
        let file = root.join(path);
        let current = fs::read_to_string(&file).ok();
        if current.as_deref() == Some(text.as_str()) {
            continue;
        }
        if check {
            eprintln!("abi-gen: {path} is stale; run `make -C arch/jitk/abi gen`");
            failed = true;
        } else if let Err(e) = fs::write(&file, text) {
            eprintln!("abi-gen: {path}: {e}");
            failed = true;
        } else {
            println!("abi-gen: wrote {path}");
        }
    }
    if failed {
        return ExitCode::FAILURE;
    }
    if check {
        println!("abi-gen: 4 generated files match jitk-abi v{ABI_VERSION}");
    }
    ExitCode::SUCCESS
}

#[cfg(test)]
mod tests {
    use super::expand;
    #[test]
    fn templates_expand_known_placeholders_only() {
        assert_eq!(
            expand("{{! note }}\nfd {{FD_FINISH}}, {{MAX_CALLS}}\n", "t").unwrap(),
            "fd 102, 32\n"
        );
        assert!(expand("{{NOPE}}", "t").is_err());
        assert!(expand("{{FD_FINISH", "t").is_err());
    }
}
