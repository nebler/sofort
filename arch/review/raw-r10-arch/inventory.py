"""R10 owned-file inventory: every git-tracked file under arch/jitk, classified.

Usage: python3 -I inventory.py <arch/jitk> <out.json>
Kinds: code, test, config/data, docs, evidence, generated, vendor/lock/patch, binary, other.
Line counts are physical newlines (comments/blanks included), like count-loc.
"""
import collections, json, os, re, subprocess, sys

root, out = sys.argv[1], sys.argv[2]
files = [f for f in subprocess.check_output(['git', 'ls-files', '-z'], cwd=root).decode().split('\0') if f]
CODE_EXT = {'.rs', '.S', '.s', '.c', '.h', '.ts', '.mjs', '.js', '.cjs', '.sh', '.ld', '.sb', '.lua', '.toml', '.mk', '.py'}
EVID_DIR = re.compile(r'(^|/)(results|raw[-_][^/]*|evidence|ledger|test-results|experiments|e2-controls|results-fs|out|repros|phase2-grown|pathfs-grown)(/|$)')
TEST_RE = re.compile(r'(^|/)(tests?|fixtures|hostile|harness|stress|nested)(/|$)|(^|/)[^/]*(test|check|hostile|probe|conformance|type-proof|verify|smoke)[^/]*$', re.I)
SPLITS = ['vmm/sandbox', 'executor/policy', 'executor/ipc', 'executor/vendor', 'bench/hyperlight', 'bench/linux-memory',
          'kernel/src/arch', 'kernel/src/syscalls', 'kernel/src', 'shard/src', 'shard/guest', 'shard/harness',
          'grow/oracle', 'grow/payload', 'grow/tests']


def comp(f):
    for pre in SPLITS:
        if f.startswith(pre + '/'):
            return pre
    p = f.split('/')
    return p[0] if len(p) > 1 else '(root)'


def kind(f):
    b = os.path.basename(f)
    ext = os.path.splitext(b)[1]
    try:
        data = open(os.path.join(root, f), 'rb').read()
    except OSError:
        return 'missing', 0, 0
    sz = len(data)
    if b'\0' in data[:8192]:
        return 'binary', 0, sz
    n = data.count(b'\n')
    if b in ('package-lock.json', 'Cargo.lock') or '/vendor/' in '/' + f or ext == '.diff' or '/patches/' in f:
        return 'vendor/lock/patch', n, sz
    if EVID_DIR.search(f) or b.startswith('RESULTS') or ext in ('.log', '.jsonl', '.csv') or \
            re.search(r'(results|raw|r4-|verification|census|summary)[^/]*\.json$', b):
        return 'evidence', n, sz
    if ext == '.md':
        return 'docs', n, sz
    if ext == '.json':
        return 'config/data', n, sz
    if 'generated' in b or b'Generated by' in data[:200] or b'DO NOT EDIT' in data[:200]:
        return 'generated', n, sz
    if ext in CODE_EXT or b in ('Makefile', 'Dockerfile', 'init'):
        return ('test' if TEST_RE.search(f) else 'code'), n, sz
    return 'other', n, sz


rows = [(comp(f), *kind(f)[:1], f, *kind(f)[1:]) for f in files]
json.dump(rows, open(out, 'w'))
agg = collections.defaultdict(collections.Counter)
agsz = collections.defaultdict(collections.Counter)
for c, k, f, n, sz in rows:
    agg[c][k] += n
    agsz[c][k] += sz
kinds = ['code', 'test', 'config/data', 'docs', 'evidence', 'generated', 'vendor/lock/patch', 'binary', 'other']
print('%-22s' % 'component' + ''.join('%11s' % k[:10] for k in kinds) + '  evMiB binMiB files')
tot, totsz = collections.Counter(), collections.Counter()
nfiles = collections.Counter(c for c, *_ in rows)
for c in sorted(agg, key=lambda c: -agg[c]['code']):
    print('%-22s' % c + ''.join('%11d' % agg[c][k] for k in kinds) +
          '  %5.1f %5.1f %5d' % (agsz[c]['evidence'] / 2**20, agsz[c]['binary'] / 2**20, nfiles[c]))
    tot.update(agg[c])
    totsz.update(agsz[c])
print('%-22s' % 'TOTAL' + ''.join('%11d' % tot[k] for k in kinds) + '  %5d' % len(rows))
print('MiB by kind', {k: round(v / 2**20, 1) for k, v in totsz.items()})
print('files by kind', collections.Counter(k for _, k, *_ in rows))
